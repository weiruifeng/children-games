"""Compile adventure groups from the retained v3 source ledger, without changing reading identities."""
import json,math,collections
from pathlib import Path
root=Path(__file__).resolve().parent.parent
data=root/'shared/src/pinyin-garden/data'
def read(name):return json.loads((data/name).read_text().split(' = ',1)[1].strip().removesuffix(';'))
readings={r['id']:r for r in read('candidate-ledger.ts')};old=read('level-ledger.ts')
levels=[];groups=collections.defaultdict(list)
for l in old:
 if l['track']=='foundation':continue
 track='challenge' if l['track']=='challenge' else 'main'
 for rid in l['targets']:
  if readings[rid]['textValidation']['status']=='source-verified':groups[track,l['chapter']].append(rid)
for id,chapter,targets in [('foundation-01',1,['a','o','e']),('foundation-04',2,['i','u','ü']),('foundation-06',2,['ā','á','ǎ','à','ǐ','ǜ'])]:
 levels.append(dict(id=id,chapter=chapter,track='foundation',name='芽芽训练场',targets=targets,short=len(targets)<4))
# Keep every prerequisite boundary: sparse challenge groups remain explicitly short side adventures.
for (track,chapter),targets in sorted(groups.items(),key=lambda kv:(kv[0][0]=='challenge',kv[0][1])):
 count=math.ceil(len(targets)/6);size,extra=divmod(len(targets),count);offset=0
 for i in range(count):
  n=size+(i<extra);part=targets[offset:offset+n];offset+=n
  levels.append(dict(id=f'{"adventure" if track=="main" else "encounter"}-{chapter:02d}-{i+1:02d}',chapter=chapter,track=track,name=f'{"花园守护" if track=="main" else "奇遇挑战"} {i+1}',targets=part,short=n<4))
byReading={r:l['id'] for l in levels if l['track']!='foundation' for r in l['targets']}
mapping={}
for l in old:
 if l['track']=='foundation':mapping[l['id']]=[{'foundation-02':'foundation-01','foundation-03':'foundation-01','foundation-05':'foundation-04'}.get(l['id'],l['id'])]
 else:mapping[l['id']]=list(dict.fromkeys(byReading[r] for r in l['targets'] if r in byReading))
(data/'adventure-levels.ts').write_text('// Generated by scripts/build-garden-adventures.py; original ledger retained for migration.\nexport const adventureLevels = '+json.dumps(levels,ensure_ascii=False,indent=1)+';\n')
(data/'adventure-migration.ts').write_text('// One old lesson can map to several rebalanced adventures; never copy its completion stars.\nexport const adventureMigration:Record<string,string[]> = '+json.dumps(mapping,ensure_ascii=False,indent=1)+';\n')
report={'levels':len(levels),'readings':len(byReading),'distribution':dict(collections.Counter(len(l['targets']) for l in levels if l['track']!='foundation')),'shortAdventures':[l for l in levels if l['short'] and l['track']!='foundation'],'oldToNew':mapping}
(root/'docs/specs/pinyin-garden/content-inventory/adventure-migration.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
print({k:v for k,v in report.items() if k!='oldToNew'})
